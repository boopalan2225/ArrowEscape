import com.example.arrowescape.R

/**
 * Everything that makes a theme feel like *itself* beyond its colours: the
 * home screen's drifting scenery, its motto, its corners, and its voice.
 *
 * Adding a theme stays a two-file job - a palette in `ThemePalettes.kt` and a
 * persona here - because every screen reads these fields instead of asking
 * "which theme am I?".
 */
data class ThemePersona(
    /** Line under the title on Home. */
    val tagline: String,
    /** Glyph inside the logo core. */
    val crest: String,
    /** Glyphs that drift across the home backdrop. */
    val motes: List<String>,
    /** How many of them are on screen at once. */
    val moteCount: Int,
    /** Seconds for one mote to cross the screen - the theme's tempo. */
    val driftMillis: Int,
    /** Leaves fall, embers rise: which way the scenery travels. */
    val driftDown: Boolean,
    /** Corner rounding used by cards and buttons app-wide. */
    val corner: Dp,
    /** Tint of the soft glow behind the scenery. */
    val glow: Color,
    val sounds: SoundPack
)

/** The three clips a theme speaks with. */
data class SoundPack(
    @RawRes val success: Int,
    @RawRes val error: Int,
    @RawRes val complete: Int
)

/** The look's personality: scenery, motto, corners and voice. */
fun AppTheme.persona(): ThemePersona = when (this) {
    AppTheme.CLASSIC -> ClassicPersona
    AppTheme.MIDNIGHT -> MidnightPersona
    AppTheme.FOREST -> ForestPersona
    AppTheme.SUNSET -> SunsetPersona
}

/** Shorthand for the only part of the persona the audio layer cares about. */
fun AppTheme.soundPack(): SoundPack = persona().sounds

